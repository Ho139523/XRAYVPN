CATALOGS = {"en": EN, "fa": FA}


def t(lang, key, **params):
    """Translate `key`; falls back to English, then to the key itself."""
    text = CATALOGS.get(lang, EN).get(key) or EN.get(key) or key
    return text.format(**params) if params else text


class UserError(ValueError):
    """A problem the person can fix; carries a translation key for the web UI."""

    def __init__(self, key, **params):
        super().__init__(t("en", key, **params))
        self.key = key
        self.params = params

    def message(self, lang):
        return t(lang, self.key, **self.params)
